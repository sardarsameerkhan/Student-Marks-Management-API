CREATE TABLE courses (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(10) NOT NULL UNIQUE,
    title varchar(150) NOT NULL,
    credit_hours integer NOT NULL CHECK (credit_hours BETWEEN 1 AND 4),
    created_at_utc timestamp with time zone NOT NULL
);

CREATE TABLE students (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_no varchar(20) NOT NULL UNIQUE,
    full_name varchar(100) NOT NULL,
    email varchar(150) NOT NULL UNIQUE CHECK (email = lower(email)),
    created_at_utc timestamp with time zone NOT NULL
);

CREATE TABLE enrollments (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id integer NOT NULL REFERENCES students(id) ON DELETE RESTRICT,
    course_id integer NOT NULL REFERENCES courses(id) ON DELETE RESTRICT,
    mark integer CHECK (mark IS NULL OR (mark >= 0 AND mark <= 100)),
    enrolled_at_utc timestamp with time zone NOT NULL,
    CONSTRAINT uq_enrollments_student_course UNIQUE (student_id, course_id)
);

CREATE TABLE users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(50) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar(20) NOT NULL,
    student_id integer UNIQUE REFERENCES students(id) ON DELETE RESTRICT,
    CONSTRAINT ck_users_role_student_link CHECK (
        (role = 'Teacher' AND student_id IS NULL) OR
        (role = 'Student' AND student_id IS NOT NULL)
    )
);

CREATE INDEX ix_enrollments_course_id ON enrollments(course_id);
